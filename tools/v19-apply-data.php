// 2. Register or reuse attachment helper
function v19_register_media($relative_file, $title, $alt) {
    $upload_dir = wp_upload_dir();
    $full_path = $upload_dir['basedir'] . '/' . ltrim($relative_file, '/');
    if (!is_file($full_path)) {
        throw new RuntimeException('Missing media file: ' . $full_path);
    }
    $existing = get_posts([
        'post_type' => 'attachment',
        'post_status' => 'inherit',
        'meta_key' => '_wp_attached_file',
        'meta_value' => ltrim($relative_file, '/'),
        'posts_per_page' => 1,
        'fields' => 'ids',
    ]);
    if (!empty($existing)) {
        $id = (int) $existing[0];
        update_post_meta($id, '_wp_attachment_image_alt', $alt);
        return $id;
    }
    $filetype = wp_check_filetype($full_path, null);
    $attachment = [
        'guid' => $upload_dir['baseurl'] . '/' . ltrim($relative_file, '/'),
        'post_mime_type' => $filetype['type'] ?: 'image/png',
        'post_title' => $title,
        'post_content' => '',
        'post_status' => 'inherit',
    ];
    $id = wp_insert_attachment($attachment, $full_path);
    if (is_wp_error($id) || !$id) {
        throw new RuntimeException('wp_insert_attachment failed');
    }
    $meta = wp_generate_attachment_metadata($id, $full_path);
    if ($meta) {
        wp_update_attachment_metadata($id, $meta);
    }
    update_post_meta($id, '_wp_attachment_image_alt', $alt);
    return (int) $id;
}

